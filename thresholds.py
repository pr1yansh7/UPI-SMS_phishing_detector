"""
thresholds.py — THE single source of truth for feature suspiciousness.

Edit THIS file if:
  - A feature is being flagged as suspicious when it shouldn't be
    (false positive → raise its threshold or remove it from SUSPICIOUS_HIGH)
  - A feature is NOT being flagged when it should be
    (false negative → lower its threshold or add it to SUSPICIOUS_HIGH)
  - You added a new feature and need to define how it's flagged

Do NOT edit this file for:
  - How a feature VALUE is computed → edit the matching features/*.py file
  - CLI output formatting → predictor.py
  - Model training → trainer.py
  - Config constants (API keys, brand lists) → config.py

is_feature_suspicious() is imported by predictor.py, api.py, dashboard.py,
and tests/test_predictor.py. All suspicious-flagging logic is here and
ONLY here — there is no duplicate threshold logic anywhere else.
"""

from config import FEATURE_COLUMNS


# ── Features where HIGH value = suspicious ────────────────────────────────────
# Binary features: value == 1 means suspicious.
# Numeric features: value >= threshold (in FEATURE_WARN_THRESHOLDS) = suspicious.
SUSPICIOUS_HIGH: set[str] = {
    # A. URL Structure
    "url_length",
    "dot_count",
    "digit_ratio",
    "special_char_count",
    "subdomain_depth",
    "has_ip_address",           # binary: 1 = raw IP used instead of domain
    "has_at_symbol",            # binary: 1 = @ trick in netloc
    "url_entropy",
    "path_depth",
    "has_double_slash_in_path", # binary: 1 = double slash in path
    "has_non_standard_port",    # binary: 1 = non-80/443 port
    "sensitive_query_params",   # binary: 1 = otp/pin/token in query string
    "phish_keyword_count",
    # B. Domain
    "suspicious_tld",           # binary: 1 = .xyz/.tk/.ml etc.
    "brand_in_subdomain",       # binary: 1 = phonepe.evil.xyz
    "brand_in_path",            # binary: 1 = evil.xyz/phonepe/login
    "brand_in_hostname",        # binary: 1 = uidai-update.xyz or phonepe-kyc.xyz
    "has_homograph_chars",      # binary: 1 = Unicode lookalike chars
    "is_punycode_domain",       # binary: 1 = xn-- IDN encoding
    # C. SSL
    "is_self_signed",           # binary: 1 = issuer == subject
    # D. HTML
    "form_count",
    "password_field_count",
    "hidden_field_count",
    "external_resource_ratio",
    "html_similarity_score",
    "https_form_mismatch",      # binary: 1 = HTTPS page posts to HTTP
    "favicon_external",         # binary: 1 = favicon from external CDN
    # E. Network
    "hosting_country_suspicious",  # binary: 1 = suspicious IP range
    "asn_is_suspicious",           # binary: 1 = bulletproof hosting ASN
    # F. OSINT
    "is_url_shortener",         # binary: 1 = bit.ly / tinyurl etc.
    "google_safe_browsing",     # binary: 1 = flagged by Google
}

# ── Features where LOW value = suspicious ────────────────────────────────────
# Binary features: value == 0 means suspicious.
# Numeric features: value < threshold (in FEATURE_WARN_THRESHOLDS) = suspicious.
# -1 (unknown/not configured) is treated as NOT suspicious to avoid noise.
SUSPICIOUS_LOW: set[str] = {
    # C. SSL
    "has_https",            # 0 = plain HTTP — no encryption
    "cert_age_days",        # very new cert = phishing campaign
    "trusted_ca",           # 0 = not from a recognised CA
    # B. Domain
    "domain_age_days",      # very new domain = likely throwaway
    "min_brand_edit_distance",  # very small = typosquatting
    # E. Network
    "has_mx_record",        # 0 = no email infrastructure = throwaway domain
    # F. OSINT
    "dns_ttl",              # very low = fast-flux evasion technique
}

# ── Numeric thresholds ────────────────────────────────────────────────────────
# For SUSPICIOUS_HIGH numeric features: flag if value >= threshold.
# For SUSPICIOUS_LOW  numeric features: flag if 0 <= value < threshold.
# Binary features (value is 0 or 1) don't need entries here — they're
# handled directly in is_feature_suspicious() by set membership.
FEATURE_WARN_THRESHOLDS: dict[str, float] = {
    # A. URL Structure
    "url_length":             75,     # characters
    "dot_count":               3,     # dots in netloc
    "digit_ratio":             0.15,  # 15% of URL chars are digits
    "special_char_count":      5,     # -, _, @, %, =, ?, & combined
    "subdomain_depth":         2,     # subdomain levels
    "url_entropy":             4.5,   # bits per character
    "path_depth":              4,     # path segments
    "phish_keyword_count":     2,     # keywords in URL

    # B. Domain
    "domain_age_days":         30,    # below 30 days = suspicious
    "min_brand_edit_distance": 3,     # edit dist <= 3 = typosquatting

    # C. SSL
    "cert_age_days":           30,    # cert issued < 30 days ago = suspicious

    # D. HTML
    "form_count":              1,
    "password_field_count":    1,
    "hidden_field_count":      3,
    "external_resource_ratio": 0.6,   # 60% of resources from external domains
    "html_similarity_score":   0.3,   # 30% match to real UPI app UI

    # E. Network
    "redirect_count":          2,     # >= 2 redirects = suspicious

    # F. OSINT
    "dns_ttl":                 300,   # below 300 seconds = fast-flux
}


def is_feature_suspicious(name: str, value) -> bool:
    """
    Returns True if the given feature value is suspicious.

    This is the ONLY place in the codebase where suspicious/safe logic lives.
    Edit the sets and dict above to change flagging behaviour —
    do NOT replicate this logic anywhere else.

    Args:
        name:  Feature column name (must be in FEATURE_COLUMNS).
        value: Computed feature value (int or float).

    Returns:
        True  = flag as suspicious in the output / dashboard
        False = treat as clean or unknown
    """
    # ── Binary high-bad: value == 1 means suspicious ──────────────────────
    BINARY_HIGH_BAD = {
        "has_ip_address", "has_at_symbol", "suspicious_tld",
        "brand_in_subdomain", "brand_in_path", "brand_in_hostname", "is_self_signed",
        "hosting_country_suspicious", "is_url_shortener",
        "google_safe_browsing", "has_homograph_chars",
        "is_punycode_domain", "has_double_slash_in_path",
        "has_non_standard_port", "sensitive_query_params",
        "https_form_mismatch", "favicon_external", "asn_is_suspicious",
    }
    if name in BINARY_HIGH_BAD:
        return value == 1

    # ── Binary low-bad: value == 0 means suspicious ───────────────────────
    if name in ("has_https", "trusted_ca"):
        return value == 0

    # ── MX record: 0 = no mail server = suspicious; -1 = unknown (skip) ──
    if name == "has_mx_record":
        return value == 0

    # ── Edit distance: small value = typosquatting ────────────────────────
    if name == "min_brand_edit_distance":
        threshold = FEATURE_WARN_THRESHOLDS.get("min_brand_edit_distance", 3)
        return 0 <= value <= threshold

    # ── Numeric high-bad: value >= threshold ──────────────────────────────
    if name in SUSPICIOUS_HIGH and name in FEATURE_WARN_THRESHOLDS:
        return value >= FEATURE_WARN_THRESHOLDS[name]

    # ── Numeric low-bad: 0 <= value < threshold (-1 = unknown, skip) ─────
    if name in SUSPICIOUS_LOW and name in FEATURE_WARN_THRESHOLDS:
        return 0 <= value < FEATURE_WARN_THRESHOLDS[name]

    # ── Unknown feature name — never crash, just return clean ─────────────
    return False


def format_feature_value(name: str, value) -> str:
    """
    Format a feature value for display in the CLI or dashboard table.
    Floats are rounded to 4 decimal places; ints and -1 are shown as-is.
    """
    if isinstance(value, float):
        return f"{value:.4f}"
    return str(value)
