import logging
from urllib.parse import urlparse

import requests

from config import (
    GOOGLE_SAFE_BROWSING_API_KEY,
    REQUEST_TIMEOUT,
    SUSPICIOUS_DNS_TTL,
    URL_SHORTENERS,
)

log = logging.getLogger(__name__)

# Optional — gracefully degrade if dnspython not installed
try:
    import dns.resolver
    DNS_AVAILABLE = True
except ImportError:
    DNS_AVAILABLE = False


def is_url_shortener(url: str) -> int:
    """
    Returns 1 if the URL's domain is a known URL shortening service.

    Phishers use shorteners (bit.ly, tinyurl.com, t.co…) to:
      1. Hide the real malicious destination from cursory inspection
      2. Bypass domain-based blocklists that don't follow redirects
      3. Get click metrics on their phishing campaigns

    The check matches both exact domain (bit.ly) and subdomains (api.bit.ly).
    To add/remove shortener domains: edit URL_SHORTENERS in config.py.
    Returns 0 for all non-shortener domains.
    """
    host = urlparse(url).netloc.lower().split(":")[0]
    return int(any(host == s or host.endswith("." + s) for s in URL_SHORTENERS))


def dns_ttl(url: str) -> int:
    """
    DNS Time-To-Live (TTL) of the domain's A record, in seconds.

    Phishing infrastructure uses very low TTL values (< 300 seconds) to
    enable "fast-flux" — rapidly rotating IP addresses so that by the time
    a blocklist update deploys, the phishing server has already moved to
    a new IP and the blocklist entry is stale.

    Legitimate businesses use TTL values of 3600 seconds (1 hour) or higher
    because they don't need to change their IP rapidly.

    Returns:
      int  — TTL in seconds (low values < 300 are suspicious)
       -1  — dnspython not installed, domain unresolvable, or lookup timed out

    Install: pip install dnspython
    """
    if not DNS_AVAILABLE:
        log.debug("dnspython not installed — dns_ttl returning -1. Run: pip install dnspython")
        return -1
    host = urlparse(url).netloc.split(":")[0].rstrip(".")
    try:
        answers = dns.resolver.resolve(host, "A", lifetime=5)
        return int(answers.rrset.ttl)
    except Exception as e:
        log.debug(f"DNS TTL lookup failed for {host}: {e}")
        return -1


def google_safe_browsing(url: str) -> int:
    """
    Queries the Google Safe Browsing API v4 to check whether the URL is
    already flagged as phishing, malware, or unwanted software by Google's
    threat intelligence team.

    This adds a real-world threat-intel layer on top of the ML model —
    if Google's blocklist already knows about this URL, we catch it regardless
    of what the ML model scores.

    Returns:
      1  — URL is flagged by Google Safe Browsing
      0  — URL is clean according to Google
     -1  — GOOGLE_SAFE_BROWSING_API_KEY not configured (set in .env)

    Get a free API key:
      https://console.cloud.google.com → search "Safe Browsing API" →
      Enable → Credentials → Create API Key → paste into .env

    To add/remove threat types checked:
      edit the 'threatTypes' list in the payload below.
    """
    if GOOGLE_SAFE_BROWSING_API_KEY == "YOUR_GOOGLE_SAFE_BROWSING_API_KEY":
        return -1

    endpoint = (
        "https://safebrowsing.googleapis.com/v4/threatMatches:find"
        f"?key={GOOGLE_SAFE_BROWSING_API_KEY}"
    )
    payload = {
        "client": {
            "clientId":      "upi-phish-detector",
            "clientVersion": "1.0",
        },
        "threatInfo": {
            "threatTypes":      ["MALWARE", "SOCIAL_ENGINEERING", "UNWANTED_SOFTWARE"],
            "platformTypes":    ["ANY_PLATFORM"],
            "threatEntryTypes": ["URL"],
            "threatEntries":    [{"url": url}],
        },
    }
    try:
        resp = requests.post(endpoint, json=payload, timeout=REQUEST_TIMEOUT)
        resp.raise_for_status()
        # 'matches' key is only present when at least one threat was found
        return 1 if resp.json().get("matches") else 0
    except requests.RequestException as e:
        log.warning(f"Google Safe Browsing API error for {url}: {e}")
        return -1
