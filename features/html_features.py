"""
features/html_features.py — HTML Content features (Group D, 7 features).

Edit THIS file if any of these give wrong results:
  form_count, password_field_count, hidden_field_count,
  external_resource_ratio, html_similarity_score,
  https_form_mismatch, favicon_external

Do NOT edit this file for:
  - URL structure checks → url_features.py
  - Domain checks → domain_features.py
  - SSL checks → ssl_features.py
  - Network/OSINT → network_features.py / osint_features.py
  - Adding/removing UPI brand names or UI strings → config.py

Note: all functions in this module accept a pre-parsed BeautifulSoup object
(or None), NOT a raw URL. The HTTP fetch is done once in feature_extractor.py
and shared across all HTML functions to avoid hitting the server 7 times.
"""

import logging
from typing import Optional
from urllib.parse import urlparse

from bs4 import BeautifulSoup

from config import UPI_BRANDS

log = logging.getLogger(__name__)

# UPI + Aadhaar app UI strings that phishing pages copy from the real apps
_UPI_UI_STRINGS = [
    # UPI strings
    "enter upi pin", "upi id", "mobile number", "send money",
    "request money", "scan qr", "pay now", "virtual payment address",
    # Aadhaar strings
    "enter aadhaar number", "aadhaar otp", "biometric authentication",
    "update aadhaar", "download e-aadhaar", "link aadhaar",
    "enrollment id", "uidai", "unique identification",
    "aadhaar card", "masked aadhaar",
]

# Logo image filename patterns that phishing pages hotlink from real CDNs
_LOGO_PATTERNS = [
    # UPI logos
    "phonepe-logo", "gpay-logo", "paytm-logo", "bhim-logo",
    # Aadhaar / UIDAI logos
    "uidai-logo", "aadhaar-logo", "digilocker-logo",
    "maadhaar-logo", "aadhaar_logo", "uidai_logo",
]


def form_count(soup: Optional[BeautifulSoup]) -> int:
    """
    Number of <form> elements on the page.
    Phishing pages revolve around credential-harvesting forms.
    Even a single form on a payment-branded page is a meaningful signal
    when combined with password_field_count.
    Returns 0 if soup is None (page could not be fetched).
    """
    return len(soup.find_all("form")) if soup else 0


def password_field_count(soup: Optional[BeautifulSoup]) -> int:
    """
    Number of <input type="password"> fields on the page.
    A direct indicator of credential theft — real UPI app pages delivered
    to end users don't contain raw password inputs in their HTML.
    Returns 0 if soup is None.
    """
    return len(soup.find_all("input", {"type": "password"})) if soup else 0


def hidden_field_count(soup: Optional[BeautifulSoup]) -> int:
    """
    Number of <input type="hidden"> fields.
    Phishing pages use hidden fields to silently bundle stolen data
    (session tokens, redirect URLs, campaign tracking IDs) alongside
    the credential form submission so the attacker's server receives
    everything in one POST.
    Returns 0 if soup is None.
    """
    return len(soup.find_all("input", {"type": "hidden"})) if soup else 0


def external_resource_ratio(soup: Optional[BeautifulSoup], url: str) -> float:
    """
    Ratio of external resources (scripts, images, stylesheets) to total resources.
    Phishing pages commonly hotlink assets directly from the real app's CDN
    (PhonePe brand logo, official CSS) so the page looks visually authentic
    while being hosted on a completely different domain.
    A ratio > 0.6 means most assets come from external domains — suspicious
    when the host domain is not the real UPI app's domain.
    Returns 0.0 if soup is None or no resource tags exist.
    """
    if not soup:
        return 0.0
    host = urlparse(url).netloc
    srcs = [
        tag.get("src", "") or tag.get("href", "")
        for tag in soup.find_all(["script", "img", "link"])
    ]
    srcs = [s for s in srcs if s]
    if not srcs:
        return 0.0
    external = sum(1 for s in srcs if host not in s and s.startswith("http"))
    return round(external / len(srcs), 4)


def html_similarity_score(soup: Optional[BeautifulSoup]) -> float:
    """
    Heuristic score (0.0–1.0) measuring how closely the page content
    resembles a real UPI app page.

    Checks for:
      - UPI brand names in visible text
      - Known UPI UI strings ("Enter UPI PIN", "Virtual Payment Address", etc.)
      - Logo image filename patterns used by real apps

    Higher score = more UPI-like content. This is suspicious when the score
    is high on a non-legitimate domain (phisher copied the real app's UI).

    Threshold for suspicion: > 0.3

    Note: this is a keyword-based heuristic. A production system would use
    perceptual image hashing of screenshots — see PAPER.md §7 Future Work.
    To add/remove UI strings: edit _UPI_UI_STRINGS at the top of this file.
    To add/remove brand names: edit UPI_BRANDS in config.py.
    Returns 0.0 if soup is None.
    """
    if not soup:
        return 0.0
    text     = soup.get_text(separator=" ").lower()
    html_str = str(soup).lower()
    signals, total = 0, 0

    for brand in UPI_BRANDS:
        total += 1
        if brand in text:
            signals += 1

    for ui_str in _UPI_UI_STRINGS:
        total += 1
        if ui_str in text:
            signals += 1

    for pattern in _LOGO_PATTERNS:
        total += 1
        if pattern in html_str:
            signals += 1

    return round(signals / total, 4) if total else 0.0


def https_form_mismatch(soup: Optional[BeautifulSoup], url: str) -> int:
    """
    Returns 1 if the page is served over HTTPS but any <form action>
    attribute posts to a plain HTTP endpoint.

    This is a classic credential-theft pattern:
      1. Page loads over HTTPS so the browser shows the padlock.
      2. The form submits to http://attacker.xyz/collect in plaintext.
    The victim sees HTTPS = trusted, but their credentials travel unencrypted.

    Returns 0 if:
      - soup is None
      - Page is HTTP (check doesn't apply)
      - All form actions post to HTTPS or relative URLs
    """
    if not soup:
        return 0
    if urlparse(url).scheme != "https":
        return 0
    for form in soup.find_all("form"):
        action = form.get("action", "")
        if action.startswith("http://"):
            return 1
    return 0


def favicon_external(soup: Optional[BeautifulSoup], url: str) -> int:
    """
    Returns 1 if the page's favicon is loaded from an external domain.
    Phishers steal the official PhonePe / Paytm / GPay favicon from the
    real app's CDN so that the browser tab shows the authentic icon,
    making the tab visually indistinguishable from a real session.

    Only <link rel="icon"> / <link rel="shortcut icon"> tags are checked.
    Internal favicons (/favicon.ico) return 0.
    Returns 0 if soup is None.
    """
    if not soup:
        return 0
    host = urlparse(url).netloc
    for link in soup.find_all("link"):
        rel = link.get("rel", [])
        if isinstance(rel, list):
            rel = " ".join(rel)
        if "icon" in rel.lower():
            href = link.get("href", "")
            if href.startswith("http") and host not in href:
                return 1
    return 0
