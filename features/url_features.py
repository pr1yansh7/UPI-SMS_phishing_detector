"""
features/url_features.py — URL Structure features (Group A, 13 features).

Edit THIS file if any of these give wrong results:
  url_length, dot_count, digit_ratio, special_char_count,
  subdomain_depth, has_ip_address, has_at_symbol, url_entropy,
  path_depth, has_double_slash_in_path, has_non_standard_port,
  sensitive_query_params, phish_keyword_count

Do NOT edit this file for:
  - Domain checks (TLD, brand, edit distance) → domain_features.py
  - SSL checks → ssl_features.py
  - HTML checks → html_features.py
  - Network/OSINT checks → network_features.py / osint_features.py
  - Adding/removing keywords or sensitive params → config.py
"""

import ipaddress
import math
from urllib.parse import parse_qs, urlparse

from config import PHISH_KEYWORDS, SENSITIVE_PARAMS


def url_length(url: str) -> int:
    """
    Total character length of the URL.
    Phishing URLs are often padded with extra path segments and parameters
    to look legitimate, pushing them well above 75 characters.
    """
    return len(url)


def dot_count(url: str) -> int:
    """
    Number of dots in the netloc (hostname + port).
    Multiple dots indicate subdomain stacking: pay.phonepe.fake.xyz = 3 dots.
    Legitimate UPI apps use at most 2 dots (www.phonepe.com).
    """
    return urlparse(url).netloc.count(".")


def digit_ratio(url: str) -> float:
    """
    Proportion of characters in the URL that are digits.
    Phishing domains often embed numbers to avoid blocklist keyword matching.
    Threshold: > 0.15 is suspicious.
    """
    if not url:
        return 0.0
    digits = sum(c.isdigit() for c in url)
    return round(digits / len(url), 4)


def special_char_count(url: str) -> int:
    """
    Count of suspicious special characters: -, _, @, %, =, ?, &
    Phishing URLs overload these to pad length and confuse parsers.
    """
    return sum(url.count(c) for c in ["-", "_", "@", "%", "=", "?", "&"])


def subdomain_depth(url: str) -> int:
    """
    Number of subdomain levels above the registered domain.
    phonepe.evil.xyz → depth 1
    pay.phonepe.upi.evil.xyz → depth 2
    Legitimate sites rarely exceed depth 1 (www).
    """
    host = urlparse(url).netloc.split(":")[0]
    parts = host.split(".")
    return max(0, len(parts) - 2)


def has_ip_address(url: str) -> int:
    """
    Returns 1 if the host is a raw IP address instead of a domain name.
    Legitimate services never expose raw IPs to end users.
    """
    host = urlparse(url).netloc.split(":")[0]
    try:
        ipaddress.ip_address(host)
        return 1
    except ValueError:
        return 0


def has_at_symbol(url: str) -> int:
    """
    Returns 1 if the netloc contains @.
    Trick: http://real.com@evil.com → browser navigates to evil.com.
    The part before @ is silently treated as credentials and ignored.
    """
    return 1 if "@" in urlparse(url).netloc else 0


def url_entropy(url: str) -> float:
    """
    Shannon entropy of the entire URL string.
    High entropy (> 4.5 bits/char) means the URL looks randomised or
    machine-generated, which is common in phishing infrastructure.
    """
    if not url:
        return 0.0
    freq: dict = {}
    for ch in url:
        freq[ch] = freq.get(ch, 0) + 1
    entropy = -sum((f / len(url)) * math.log2(f / len(url)) for f in freq.values())
    return round(entropy, 4)


def path_depth(url: str) -> int:
    """
    Number of non-empty path segments.
    /phonepe/kyc/verify/otp/step2 = depth 5.
    Phishing pages fabricate deep paths to mimic app navigation flows.
    Threshold: > 4 is suspicious.
    """
    path = urlparse(url).path
    return len([p for p in path.split("/") if p])


def has_double_slash_in_path(url: str) -> int:
    """
    Returns 1 if the URL path contains //.
    Double slashes confuse URL parsers and some blocklist pattern matchers,
    e.g. http://evil.xyz//phonepe//login normalises differently across tools.
    Note: the // in http:// is in the scheme, not the path — correctly excluded.
    """
    return 1 if "//" in urlparse(url).path else 0


def has_non_standard_port(url: str) -> int:
    """
    Returns 1 if the URL uses a port other than 80 (HTTP) or 443 (HTTPS).
    Phishing pages on non-standard ports (8080, 8443, 3000…) hide behind
    proxies or use ports that corporate firewalls don't inspect.
    """
    port = urlparse(url).port
    return 1 if port and port not in (80, 443) else 0


def sensitive_query_params(url: str) -> int:
    """
    Returns 1 if the URL query string contains sensitive parameter names
    (token, otp, pin, upi_id, password, etc.).
    Legitimate payment apps NEVER transmit credentials in URLs — phishing
    pages do this to log them in web server access logs on their end.
    """
    params = parse_qs(urlparse(url).query)
    return int(any(k.lower() in SENSITIVE_PARAMS for k in params))


def phish_keyword_count(url: str) -> int:
    """
    Count how many UPI-phishing keywords appear in the full URL.
    Keywords include: verify, kyc, otp, pin, cashback, reward, urgent…
    Multiple keywords in one URL is a very strong signal — real apps
    don't pack all these terms into a single link.
    Threshold: >= 2 keywords is suspicious.
    """
    lower = url.lower()
    return sum(1 for kw in PHISH_KEYWORDS if kw in lower)
