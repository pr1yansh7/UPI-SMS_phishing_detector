import logging
import socket
from typing import Optional
from urllib.parse import urlparse

import requests

from config import REQUEST_TIMEOUT, SHADY_ASNS, USER_AGENT

log = logging.getLogger(__name__)

# Optional — gracefully degrade if ipwhois not installed
try:
    from ipwhois import IPWhois
    IPWHOIS_AVAILABLE = True
except ImportError:
    IPWHOIS_AVAILABLE = False

# Optional — gracefully degrade if dnspython not installed
try:
    import dns.resolver
    DNS_AVAILABLE = True
except ImportError:
    DNS_AVAILABLE = False

# IP range prefixes commonly associated with phishing hosting / bulletproof providers.
# This is a rough heuristic. Replace with MaxMind GeoLite2 for production accuracy.
_SUSPICIOUS_IP_PREFIXES = [
    "185.", "91.108.", "5.188.", "46.161.",
]


def redirect_count(url: str) -> int:
    """
    Number of HTTP redirects followed before reaching the final page.
    Phishing campaigns often chain redirects through:
      1. A legitimate-looking URL shortener
      2. A "landing page" that checks if the visitor is the right target
      3. The actual credential-harvesting page
    Each redirect adds one count. Threshold: >= 2 is suspicious.
    Returns 0 if the request fails.
    """
    try:
        resp = requests.get(
            url,
            timeout=REQUEST_TIMEOUT,
            headers={"User-Agent": USER_AGENT},
            allow_redirects=True,
            verify=False,
        )
        return len(resp.history)
    except Exception as e:
        log.debug(f"redirect_count failed for {url}: {e}")
        return 0


def hosting_country_suspicious(url: str) -> int:
    """
    Heuristic check: returns 1 if the domain resolves to an IP address
    in a range commonly associated with phishing hosting infrastructure.

    This is a rough IP prefix check. For accurate geolocation, install
    the MaxMind GeoLite2 database (free) and replace this heuristic with
    a GeoIP lookup. Instructions in PAPER.md §7 Future Work.

    Returns 1 (suspicious) if:
      - The IP matches a known suspicious prefix
      - The domain cannot be resolved (unresolvable = suspicious)
    Returns 0 if the IP looks clean.
    """
    host = urlparse(url).netloc.split(":")[0]
    try:
        ip = socket.gethostbyname(host)
        return int(any(ip.startswith(p) for p in _SUSPICIOUS_IP_PREFIXES))
    except socket.gaierror:
        return 1  # can't resolve → suspicious


def asn_is_suspicious(url: str) -> int:
    """
    Checks if the domain is hosted on an Autonomous System (AS) known for
    bulletproof hosting — providers that deliberately ignore abuse complaints,
    making them a preferred choice for phishing infrastructure operators.

    Returns:
      1  — ASN is in the SHADY_ASNS list (config.py)
      0  — ASN looks clean
     -1  — lookup failed (ipwhois not installed, or network error)

    To add/remove ASNs: edit SHADY_ASNS in config.py.
    Install: pip install ipwhois
    """
    if not IPWHOIS_AVAILABLE:
        log.debug("ipwhois not installed — asn_is_suspicious returning -1. Run: pip install ipwhois")
        return -1
    host = urlparse(url).netloc.split(":")[0]
    try:
        ip     = socket.gethostbyname(host)
        result = IPWhois(ip).lookup_rdap(depth=1)
        asn    = f"AS{result.get('asn', '')}"
        return int(asn in SHADY_ASNS)
    except Exception as e:
        log.debug(f"ASN lookup failed for {host}: {e}")
        return -1


def has_mx_record(url: str) -> int:
    """
    Returns 1 if the domain has MX (mail exchange) DNS records, 0 if not.

    Legitimate businesses have email infrastructure — their domains always
    have MX records. Phishing domains registered purely for a single
    campaign almost never set up email, so the absence of an MX record
    (value = 0) is a meaningful negative signal.

    Returns:
      1  — MX record found (the domain has mail infrastructure)
      0  — No MX record (suspicious — no email = likely a throwaway domain)
     -1  — dnspython not installed or DNS query timed out

    Install: pip install dnspython
    """
    if not DNS_AVAILABLE:
        log.debug("dnspython not installed — has_mx_record returning -1. Run: pip install dnspython")
        return -1
    host = urlparse(url).netloc.split(":")[0].rstrip(".")
    try:
        dns.resolver.resolve(host, "MX", lifetime=5)
        return 1
    except Exception:
        return 0  # no MX record = suspicious
