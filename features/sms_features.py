"""
features/sms_features.py — SMS Phishing Detection features (Group G).

Detects phishing via SMS text content — the most common real-world
attack vector for UPI and Aadhaar fraud in India. 80% of Aadhaar fraud
starts with a fake SMS, not a phishing URL.

Edit THIS file if any of these give wrong results:
  sms_urgency_score, has_url_in_sms, sender_id_spoofed,
  sms_phish_keyword_count, sms_impersonates_brand,
  sms_asks_for_otp, sms_threatens_account,
  sms_hinglish_phish_score

Do NOT edit this file for:
  - URL-based features → url_features.py / domain_features.py
  - Adding keywords → config.py (SMS_PHISH_KEYWORDS)
"""

import re
from urllib.parse import urlparse

from config import (
    SMS_ACCOUNT_THREAT_PATTERNS,
    SMS_OTP_REQUEST_PATTERNS,
    SMS_URL_PATTERN,
    SMS_PHISH_KEYWORDS,
    SMS_PHISH_KEYWORDS_HINDI,
    SMS_PHISH_KEYWORDS_TAMIL,
    SMS_PHISH_KEYWORDS_TELUGU,
    SMS_PHISH_KEYWORDS_BENGALI,
    SMS_URGENCY_PHRASES,
    SMS_FAKE_SENDER_IDS,
    UPI_BRANDS,
)


def sms_urgency_score(text: str) -> float:
    """
    Score how many urgency / social-engineering manipulation phrases
    appear in the SMS text. Phishing SMSes are designed to panic the
    recipient into acting immediately without thinking.

    Returns a float 0.0–1.0 (ratio of urgency phrases found vs total list).
    Score > 0.3 is suspicious.

    Examples of urgency phrases: 'immediately', 'suspended', 'blocked',
    'expire within 24 hours', 'last chance', 'urgent action required'.
    """
    if not text:
        return 0.0
    lower = text.lower()
    hits  = sum(1 for phrase in SMS_URGENCY_PHRASES if phrase in lower)
    return round(hits / len(SMS_URGENCY_PHRASES), 4)


def has_url_in_sms(text: str) -> int:
    """
    Returns 1 if the SMS contains any URL (http/https/short links).
    Legitimate OTP SMSes from UIDAI, banks and UPI apps never contain URLs.
    Pattern lives in config.py (SMS_URL_PATTERN).
    """
    if not text:
        return 0
    return 1 if re.search(SMS_URL_PATTERN, text, re.IGNORECASE) else 0


def sender_id_spoofed(sender: str) -> int:
    """
    Returns 1 if the SMS sender ID mimics an official UIDAI, NPCI, bank,
    or UPI app sender ID. Phishers spoof sender IDs like 'VK-UIDAI',
    'BW-NPCI', 'AD-PAYTM' to make SMSes appear official.

    The check looks for brand keywords (UIDAI, NPCI, PAYTM etc.) appearing
    anywhere inside the sender ID string, catching patterns like:
      VK-UIDAI, BW-NPCI-FAKE, AD-PAYTM, TX-PHONEPE

    To add official brand keywords: edit SMS_FAKE_SENDER_IDS in config.py.
    """
    if not sender:
        return 0
    upper = sender.upper()
    # Check if any known brand keyword appears inside the sender ID
    brand_keywords = [s.rstrip("-") for s in SMS_FAKE_SENDER_IDS]
    return int(any(kw in upper for kw in brand_keywords))


def sms_phish_keyword_count(text: str) -> int:
    """
    Count UPI/Aadhaar-specific phishing keywords in the SMS text.
    Covers English keywords only (see sms_hinglish_phish_score for
    regional language detection).

    Threshold: >= 2 keywords in a single SMS = suspicious.
    """
    if not text:
        return 0
    lower = text.lower()
    return sum(1 for kw in SMS_PHISH_KEYWORDS if kw in lower)


def sms_impersonates_brand(text: str) -> int:
    """
    Returns 1 if the SMS text mentions a UPI or Aadhaar brand name.
    Combined with other signals (URL, urgency) this is a strong phishing indicator.

    Note: legitimate SMSes from real apps DO mention their brand name.
    Use this feature in combination — not in isolation.
    """
    if not text:
        return 0
    lower = text.lower()
    return int(any(brand in lower for brand in UPI_BRANDS))


def sms_asks_for_otp(text: str) -> int:
    """
    Returns 1 if the SMS asks the recipient to SHARE or SEND an OTP — always
    fraudulent. Patterns live in config.py (SMS_OTP_REQUEST_PATTERNS).
    """
    if not text:
        return 0
    lower = text.lower()
    return int(any(re.search(p, lower) for p in SMS_OTP_REQUEST_PATTERNS))


def sms_threatens_account(text: str) -> int:
    """
    Returns 1 if the SMS threatens blocking/suspension unless you act now.
    Patterns live in config.py (SMS_ACCOUNT_THREAT_PATTERNS).
    """
    if not text:
        return 0
    lower = text.lower()
    return int(any(re.search(p, lower) for p in SMS_ACCOUNT_THREAT_PATTERNS))


def sms_hinglish_phish_score(text: str) -> float:
    """
    Score phishing signals in Hindi, Tamil, Telugu, and Bengali.
    Indian phishing SMSes are increasingly written in regional languages
    to target less digitally-aware populations who may not recognise
    English-language warning signs.

    Returns 0.0–1.0 (ratio of regional phishing keywords found).
    Score > 0.2 is suspicious.

    Keywords cover: account, blocked, urgent, verify, OTP, Aadhaar,
    update, reward, cashback in each supported language.
    """
    if not text:
        return 0.0

    all_regional = (
        SMS_PHISH_KEYWORDS_HINDI +
        SMS_PHISH_KEYWORDS_TAMIL +
        SMS_PHISH_KEYWORDS_TELUGU +
        SMS_PHISH_KEYWORDS_BENGALI
    )
    if not all_regional:
        return 0.0

    hits = sum(1 for kw in all_regional if kw in text)
    return round(hits / len(all_regional), 4)


def analyse_sms(text: str, sender: str = "") -> dict:
    """
    Run all SMS phishing features on a single SMS message.

    Args:
        text:   The full SMS text content.
        sender: The SMS sender ID (optional, e.g. 'VK-UIDAI').

    Returns:
        dict of all SMS feature values + an overall risk_score (0.0–1.0).

    This is the master function for SMS analysis — mirrors extract_features()
    for URL analysis. Call this when you have an SMS to check, not a URL.
    """
    features = {
        "sms_urgency_score":         sms_urgency_score(text),
        "has_url_in_sms":            has_url_in_sms(text),
        "sender_id_spoofed":         sender_id_spoofed(sender),
        "sms_phish_keyword_count":   sms_phish_keyword_count(text),
        "sms_impersonates_brand":    sms_impersonates_brand(text),
        "sms_asks_for_otp":          sms_asks_for_otp(text),
        "sms_threatens_account":     sms_threatens_account(text),
        "sms_hinglish_phish_score":  sms_hinglish_phish_score(text),
    }

    # Weighted risk score
    # sms_asks_for_otp is the strongest single signal — no legitimate service
    # ever asks you to share an OTP, so this alone should flag as phishing
    score = (
        features["sms_urgency_score"]        * 0.12 +
        features["has_url_in_sms"]           * 0.18 +
        features["sender_id_spoofed"]        * 0.12 +
        min(features["sms_phish_keyword_count"] / 5, 1.0) * 0.08 +
        features["sms_impersonates_brand"]   * 0.08 +
        features["sms_asks_for_otp"]         * 0.28 +   # near-certain signal
        features["sms_threatens_account"]    * 0.12 +
        features["sms_hinglish_phish_score"] * 0.08
    )
    features["sms_risk_score"]  = round(min(score, 1.0), 4)
    features["is_phishing_sms"] = features["sms_risk_score"] >= 0.25  # lower threshold — OTP alone = 0.28

    flags = []
    if features["sms_asks_for_otp"]:
        flags.append("Asks you to share/send an OTP — no real service ever does this")
    if features["sms_threatens_account"]:
        flags.append("Threatens to block/suspend your account, UPI or Aadhaar")
    if features["has_url_in_sms"]:
        flags.append("Contains a link — real OTP/bank SMSes don't")
    if features["sender_id_spoofed"]:
        flags.append("Sender ID imitates UIDAI/NPCI/a bank/a UPI app")
    if features["sms_urgency_score"] > 0.1:
        flags.append("Uses urgency/pressure wording")
    if features["sms_phish_keyword_count"] >= 2:
        flags.append("Contains several known phishing phrases")
    if features["sms_hinglish_phish_score"] > 0.05:
        flags.append("Contains phishing wording in Hindi/Tamil/Telugu/Bengali")
    features["flags"] = flags
    features["risk_score"] = features["sms_risk_score"]
    features["is_phishing"] = features["is_phishing_sms"]

    return features
