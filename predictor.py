# ─── Model loading ────────────────────────────────────────────────────────────

def load_model(model_path: str):
    """Load a trained sklearn Pipeline from a .pkl file."""
    path = Path(model_path)
    if not path.exists():
        print(f"❌  Model not found: {model_path}")
        print(f"    Run  python trainer.py  first to train a model.")
        sys.exit(1)
    return load_model_bundle(str(path))[0]   # also sets model.feature_columns_


# ─── Core prediction ──────────────────────────────────────────────────────────

def predict_url(
    url: str,
    model,
    fetch_html: bool = True,
    verbose: bool = True,
) -> dict:
    """
    Run the full prediction pipeline for a single URL.

    Returns a dict with:
      url, label, is_phishing, probability, confidence,
      features (dict), suspicious_flags (list), source
    """
    if verbose:
        print(f"\n🔍  Analysing: {url}")
        print(f"    HTML fetch: {'enabled' if fetch_html else 'disabled (URL features only)'}")

    columns = getattr(model, "feature_columns_", FEATURE_COLUMNS)
    features = extract_features(url, fetch_html_content=fetch_html, only=columns)
    feature_vector = vectorize(features, columns)

    prob_phishing = float(model.predict_proba(feature_vector)[0][1])
    is_phishing   = prob_phishing >= PHISH_PROBABILITY_THRESHOLD
    confidence    = prob_phishing if is_phishing else (1 - prob_phishing)

    suspicious_flags = [
        name for name in columns
        if is_feature_suspicious(name, features.get(name, 0))
    ]

    result = {
        "url":              url,
        "label":            "PHISHING" if is_phishing else "LEGITIMATE",
        "is_phishing":      is_phishing,
        "probability":      round(prob_phishing, 4),
        "confidence":       round(confidence, 4),
        "features":         features,
        "suspicious_flags": suspicious_flags,
        "source":           "ml_model",
    }

    result = apply_allowlist(result)   # official HTTPS domains are never flagged

    if verbose:
        _print_result(result)

    return result


# ─── Terminal output ──────────────────────────────────────────────────────────

def _print_result(result: dict) -> None:
    """
    Pretty-print a prediction result to stdout.
    Edit this function to change terminal output formatting only.
    Suspicious-flag logic lives in thresholds.py, not here.
    """
    is_phishing = result["is_phishing"]
    prob        = result["probability"]
    conf        = result["confidence"] * 100
    flags       = result["suspicious_flags"]

    print()
    if is_phishing:
        print(f"  🚨  PHISHING   (confidence: {conf:.1f}%  |  p={prob:.4f})")
        print(f"      {'─'*52}")
        print(f"      {len(flags)} suspicious signal(s) detected.")
        print(f"      DO NOT enter any credentials or personal data.")
        print(f"      Report: " + "  ·  ".join(f"{c['name']}: {c['contact']}" for c in REPORTING_CHANNELS[:3]))
    else:
        print(f"  ✅  LEGITIMATE  (confidence: {conf:.1f}%  |  p_phish={prob:.4f})")
        print(f"      {'─'*52}")
        if flags:
            print(f"      {len(flags)} minor signal(s) — stay cautious.")
        else:
            print(f"      No suspicious signals detected.")

    print()
    print(f"  {'Feature':<35} {'Value':<12} Status")
    print(f"  {'─'*35} {'─'*12} {'─'*14}")
    for name in result["features"]:
        val  = result["features"].get(name, 0)
        susp = is_feature_suspicious(name, val)
        print(f"  {name:<35} {format_feature_value(name,val):<12} {'⚠  suspicious' if susp else '✓'}")

    if flags:
        print()
        top = ", ".join(flags[:5])
        print(f"  ⚠  Top risk factors: {top}")
    print()


# ─── Batch mode ───────────────────────────────────────────────────────────────

def predict_batch(
    urls_file: str,
    model,
    output_csv: str = "results/batch_predictions.csv",
    fetch_html: bool = True,
) -> None:
    """Predict a list of URLs from a text file (one URL per line)."""
    path = Path(urls_file)
    if not path.exists():
        print(f"❌  File not found: {urls_file}")
        sys.exit(1)

    urls = [line.strip() for line in path.read_text().splitlines() if line.strip()]
    print(f"📋  Batch prediction: {len(urls)} URLs")
    print(f"    Output: {output_csv}\n")

    results = []
    for i, url in enumerate(urls, 1):
        print(f"  [{i}/{len(urls)}] ", end="", flush=True)
        result = predict_url(url, model, fetch_html=fetch_html, verbose=False)
        icon   = "🚨" if result["is_phishing"] else "✅"
        print(f"{icon}  {url[:70]}  →  {result['label']}  ({result['confidence']*100:.1f}%)")
        results.append(result)

    Path(output_csv).parent.mkdir(parents=True, exist_ok=True)
    with open(output_csv, "w", newline="") as f:
        fieldnames = ["url", "label", "probability", "confidence", "suspicious_flags"]
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        for r in results:
            writer.writerow({
                "url":              r["url"],
                "label":            r["label"],
                "probability":      r["probability"],
                "confidence":       r["confidence"],
                "suspicious_flags": "|".join(r["suspicious_flags"]),
            })

    phish_count = sum(1 for r in results if r["is_phishing"])
    print(f"\n  Summary: {phish_count}/{len(results)} URLs flagged as phishing.")
    print(f"  Results → {output_csv}")


# ─── CLI entry point ──────────────────────────────────────────────────────────

def main() -> None:
    parser = argparse.ArgumentParser(
        description="UPI Phishing Detector — CLI predictor",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Examples:
  python predictor.py --url "http://phonepe-kyc.xyz/login"
  python predictor.py --url "https://paytm.com/" --no-html
  python predictor.py --batch data/urls_to_check.txt
  python predictor.py --batch data/urls.txt --output results/out.csv
        """,
    )
    parser.add_argument("--url",    help="Single URL to classify")
    parser.add_argument("--batch",  help="Text file: one URL per line")
    parser.add_argument("--model",  default=f"{MODEL_DIR}best_model.pkl")
    parser.add_argument("--output", default="results/batch_predictions.csv")
    parser.add_argument("--no-html", action="store_true",
                        help="Skip HTML fetch (faster, URL features only)")
    args = parser.parse_args()

    if not args.url and not args.batch:
        parser.print_help()
        sys.exit(0)

    model      = load_model(args.model)
    fetch_html = not args.no_html

    if args.url:
        predict_url(args.url, model, fetch_html=fetch_html, verbose=True)
    elif args.batch:
        predict_batch(args.batch, model, output_csv=args.output, fetch_html=fetch_html)


if __name__ == "__main__":
    main()
