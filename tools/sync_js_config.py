"""
tools/sync_js_config.py — generate static/upi-config.js FROM config.py.

config.py is the single source of truth. The browser copy is generated so the two
can never drift apart (they did before: e.g. the shortener list had 11 vs 15 entries).

    python tools/sync_js_config.py        # rewrite static/upi-config.js
    make sync-js                          # same thing

tests/test_js_parity.py fails if the generated file is out of date.
"""

import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

import config as C  # noqa: E402

OUT = ROOT / "static" / "upi-config.js"
EXT_OUT = ROOT / "extension" / "config.js"

HEADER = """/* ════════════════════════════════════════════════════════════════════════
   upi-config.js — AUTO-GENERATED from config.py by tools/sync_js_config.py
   DO NOT EDIT BY HAND. To change a brand / keyword / pattern list:
     1. edit config.py
     2. run:  make sync-js      (or: python tools/sync_js_config.py)
   ════════════════════════════════════════════════════════════════════════ */
"""


def _j(value) -> str:
    return json.dumps(value, ensure_ascii=False, indent=2)


def render() -> str:
    lists = [
        ("UPI_BRANDS", list(C.UPI_BRANDS.keys())),
        ("REAL_UPI_DOMAINS", list(C.REAL_UPI_DOMAINS)),
        ("SUSPICIOUS_TLDS", sorted(C.SUSPICIOUS_TLDS)),
        ("PHISH_KEYWORDS", list(C.PHISH_KEYWORDS)),
        ("URL_SHORTENERS", sorted(C.URL_SHORTENERS)),
        ("OFFICIAL_DOMAINS", list(C.OFFICIAL_DOMAINS)),
        ("SMS_URL_PATTERN", C.SMS_URL_PATTERN),
        ("SMS_OTP_REQUEST_PATTERNS", list(C.SMS_OTP_REQUEST_PATTERNS)),
        ("SMS_ACCOUNT_THREAT_PATTERNS", list(C.SMS_ACCOUNT_THREAT_PATTERNS)),
        ("SMS_PHISH_KEYWORDS", list(C.SMS_PHISH_KEYWORDS)),
        ("SMS_URGENCY_PHRASES", list(C.SMS_URGENCY_PHRASES)),
        ("SMS_FAKE_SENDER_IDS", list(C.SMS_FAKE_SENDER_IDS)),
        ("SMS_PHISH_KEYWORDS_HINDI", list(C.SMS_PHISH_KEYWORDS_HINDI)),
        ("SMS_PHISH_KEYWORDS_TAMIL", list(C.SMS_PHISH_KEYWORDS_TAMIL)),
        ("SMS_PHISH_KEYWORDS_TELUGU", list(C.SMS_PHISH_KEYWORDS_TELUGU)),
        ("SMS_PHISH_KEYWORDS_BENGALI", list(C.SMS_PHISH_KEYWORDS_BENGALI)),
        ("WA_URL_PATTERN", C.WA_URL_PATTERN),
        ("UPI_LINK_PATTERN", C.UPI_LINK_PATTERN),
        ("WA_PATTERNS", C.WA_PATTERNS),
        ("WA_PATTERN_WEIGHTS", C.WA_PATTERN_WEIGHTS),
        ("UPI_KNOWN_HANDLES", list(C.UPI_KNOWN_HANDLES)),
        ("UPI_VPA_BAIT_WORDS", list(C.UPI_VPA_BAIT_WORDS)),
        ("UPI_NOTE_BAIT_WORDS", list(C.UPI_NOTE_BAIT_WORDS)),
        ("UPI_PAYEE_TERMS", list(C.UPI_PAYEE_TERMS)),
        ("REPORTING_CHANNELS", list(C.REPORTING_CHANNELS)),
    ]
    out = [HEADER,
           "const API_BASE = 'http://localhost:5050';",
           f"const PHISH_THRESHOLD = {C.PHISH_PROBABILITY_THRESHOLD};",
           f"const WA_PHISHING_THRESHOLD = {C.WA_PHISHING_THRESHOLD};",
           ""]
    for name, value in lists:
        out.append(f"const {name} = {_j(value)};\n")
    out.append(f"const SENSITIVE_PARAMS = new Set({_j(sorted(C.SENSITIVE_PARAMS))});\n")
    return "\n".join(out)


EXT_HEADER = """/* AUTO-GENERATED by tools/sync_js_config.py from config.py — DO NOT EDIT BY HAND (make sync-js). */
"""


def render_extension() -> str:
    cfg = {
        "API_BASE": "http://localhost:5050",
        "BLOCK_THRESHOLD": 0.90,
        "OFFICIAL_DOMAINS": list(C.OFFICIAL_DOMAINS),
        "REPORTING_CHANNELS": list(C.REPORTING_CHANNELS),
    }
    return EXT_HEADER + f"const EXT_CONFIG = {_j(cfg)};\n"


if __name__ == "__main__":
    OUT.write_text(render(), encoding="utf-8")
    EXT_OUT.write_text(render_extension(), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} and {EXT_OUT.relative_to(ROOT)}")
