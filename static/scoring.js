// HTTPS + exact official host or real subdomain. Lookalikes such as
// uidai.gov.in.evil.xyz, evil-uidai.gov.in, uidai.gov.in@evil.xyz all fail.
function isOfficialDomain(url) {
  if (!url) return false;
  let u;
  try { u = new URL(url.indexOf('://') !== -1 ? url : 'https://' + url); } catch (e) { return false; }
  if (u.protocol !== 'https:') return false;
  const host = u.hostname.toLowerCase().replace(/\.$/, '');
  return OFFICIAL_DOMAINS.some(d => host === d || host.endsWith('.' + d));
}
