// ── API call (falls back to heuristic) ──────────────────────────
async function fetchPrediction(url) {
  try {
    const resp = await fetch(`${API_BASE}/predict`, {
      method: 'POST',
      headers: {'Content-Type':'application/json'},
      body: JSON.stringify({url, fetch_html: false}),
      signal: AbortSignal.timeout(4000),
    });
    if (resp.ok) return await resp.json();
  } catch(e) { /* backend not running — use heuristic */ }

  const features = computeFeatures(url);
  const prob     = scoreToProbability(features);
  const official = isOfficialDomain(url);
  const isPhish  = prob >= PHISH_THRESHOLD;
  const flags    = Object.keys(features).filter(k => isSuspicious(k, features[k]));
  const out = {
    url, features, probability: +prob.toFixed(4),
    is_phishing: isPhish,
    label: isPhish ? 'PHISHING' : 'LEGITIMATE',
    confidence: +(isPhish ? prob : 1 - prob).toFixed(4),
    suspicious_flags: flags,
    official_domain: official,
    source: 'heuristic',
  };
  if (official && isPhish) {          // official HTTPS domains are never flagged
    out.model_probability = out.probability;
    out.probability = Math.min(out.probability, 0.05);
    out.is_phishing = false; out.label = 'LEGITIMATE';
    out.confidence = +(1 - out.probability).toFixed(4);
    out.override = 'official_domain_allowlist';
  }
  return out;
}

// ── History ──────────────────────────────────────────────────────
let history = JSON.parse(localStorage.getItem('upi_phish_history') || '[]');

function saveHistory() {
  localStorage.setItem('upi_phish_history', JSON.stringify(history.slice(0,30)));
}

function renderHistory() {
  const el = document.getElementById('historyList');
  if (!history.length) {
    el.innerHTML = '<div class="empty-history">No predictions yet — analyse a URL above.</div>';
    return;
  }
  el.innerHTML = history.map((r,i) => `
    <div class="history-row" onclick="reloadResult(${i})">
      <span class="h-icon">${r.is_phishing ? '🚨' : '✅'}</span>
      <span class="h-url">${escHtml(r.url)}</span>
      <span class="h-label ${r.is_phishing ? 'phishing' : 'legit'}">${r.label}</span>
      <span class="h-prob">${(r.probability*100).toFixed(1)}%</span>
    </div>
  `).join('');
}

function clearHistory() {
  history = [];
  saveHistory();
  renderHistory();
}

function reloadResult(i) {
  document.getElementById('urlInput').value = history[i].url;
  renderResult(history[i]);
}

// ── Render result ────────────────────────────────────────────────
function renderResult(r) {
  const isPhish = r.is_phishing;
  const prob    = r.probability;
  const conf    = (r.confidence * 100).toFixed(1);
  const flags   = r.suspicious_flags || [];
  const feats   = r.features || {};

  // Verdict card
  document.getElementById('verdictCard').className = `verdict-card ${isPhish ? 'phishing' : 'legit'}`;
  document.getElementById('verdictIcon').textContent  = isPhish ? '🚨' : '✅';
  document.getElementById('verdictLabel').textContent = isPhish ? 'PHISHING' : 'LEGITIMATE';
  document.getElementById('verdictProb').textContent  = `${(prob*100).toFixed(1)}%`;
  document.getElementById('probBar').style.width      = `${prob*100}%`;

  // Flags
  const fw = document.getElementById('flagsWrap');
  if (flags.length) {
    fw.innerHTML = `<div class="flags-title">⚠ ${flags.length} risk signal${flags.length>1?'s':''} detected</div>` +
      flags.slice(0,8).map(f => `<span class="flag-pill">${f}</span>`).join('');
  } else {
    fw.innerHTML = '<div class="flags-title" style="color:var(--safe)">✓ No suspicious signals</div>';
  }

  // Feature table
  const COLS = Object.keys(feats);
  document.getElementById('flagCount').textContent = flags.length ? `${flags.length} flagged` : '';
  const tbody = document.getElementById('featureBody');
  tbody.innerHTML = COLS.map(name => {
    const val  = feats[name];
    const susp = isSuspicious(name, val);
    const disp = typeof val === 'number' && !Number.isInteger(val) ? val.toFixed(4) : (val === -1 ? 'N/A' : val);
    return `<tr class="${susp ? 'warn' : ''}">
      <td>${name}</td>
      <td>${disp}</td>
      <td class="${susp ? 'status-warn' : 'status-ok'}">${susp ? '⚠ suspicious' : '✓'}</td>
    </tr>`;
  }).join('');

  // Bar chart
  renderChart(feats, flags);
  if (r.official_domain) {
    document.getElementById('flagsWrap').innerHTML += '<div class="flags-title" style="color:var(--safe)">✓ Official domain (HTTPS allowlist)</div>';
  }
  document.getElementById('reportPanel').innerHTML = r.is_phishing ? reportPanelHTML() : '';

  document.getElementById('result').style.display = 'block';
  document.getElementById('result').scrollIntoView({behavior:'smooth', block:'start'});
}

function renderChart(feats, flags) {
  const section = document.getElementById('chartSection');
  // Normalise values to 0-1 for bar width
  const maxes = {
    url_length: 200, dot_count: 6, digit_ratio: 0.5, special_char_count: 15,
    subdomain_depth: 4, url_entropy: 6, domain_age_days: 365, cert_age_days: 365,
    form_count: 4, password_field_count: 3, hidden_field_count: 6,
    external_resource_ratio: 1, html_similarity_score: 1, redirect_count: 5,
    dns_ttl: 3600,   // new
  };
  const binaryKeys = ['has_ip_address','has_at_symbol','suspicious_tld','brand_in_subdomain',
    'brand_in_path','has_https','is_self_signed','trusted_ca','hosting_country_suspicious'];

  const rows = Object.entries(feats).map(([name, val]) => {
    const susp  = isSuspicious(name, val);
    const max   = maxes[name] || 1;
    let pct;
    if (binaryKeys.includes(name)) pct = val * 100;
    else pct = Math.min((val < 0 ? 0 : val) / max * 100, 100);
    const disp = typeof val === 'number' && !Number.isInteger(val) ? val.toFixed(3) : (val === -1 ? 'N/A' : val);
    return `<div class="bar-row">
      <span class="bar-name">${name}</span>
      <div class="bar-track"><div class="bar-fill ${susp ? 'warn' : 'ok'}" style="width:${pct}%"></div></div>
      <span class="bar-val">${disp}</span>
    </div>`;
  }).join('');

  section.innerHTML = `<div class="chart-title">▸ Feature Values — <span style="color:var(--danger)">red = suspicious</span> / <span style="color:var(--safe)">green = OK</span></div>${rows}`;
}

// ── Main analyse function ────────────────────────────────────────
async function analyse() {
  const url = document.getElementById('urlInput').value.trim();
  if (!url) { alert('Please enter a URL first.'); return; }

  const btn = document.getElementById('analyseBtn');
  const spin = document.getElementById('spinner');
  btn.disabled = true;
  btn.textContent = 'Analysing…';
  spin.style.display = 'block';

  try {
    const result = await fetchPrediction(url);
    history.unshift(result);
    saveHistory();
    renderHistory();
    renderResult(result);
  } catch(e) {
    alert('Error: ' + e.message);
  } finally {
    btn.disabled = false;
    btn.textContent = 'Analyse';
    spin.style.display = 'none';
  }
}

function fillAndAnalyse(url) {
  document.getElementById('urlInput').value = url;
  analyse();
}

function escHtml(s) {
  return s.replace(/&/g,'&amp;').replace(/</g,'&lt;').replace(/>/g,'&gt;');
}


// ── Report panel (contacts come from config.py → REPORTING_CHANNELS) ──────
function reportPanelHTML() {
  const rows = REPORTING_CHANNELS.map(c => {
    const contact = c.url
      ? '<a href="' + escHtml(c.url) + '" target="_blank" rel="noopener">' + escHtml(c.contact) + '</a>'
      : '<strong>' + escHtml(c.contact) + '</strong>';
    return '<div class="report-row"><div class="report-name">' + escHtml(c.name) + ' — ' + contact +
           '</div><div class="report-when">' + escHtml(c.when) + '</div></div>';
  }).join('');
  return '<div class="report-panel"><div class="report-title">🛟 What to do now</div>' + rows +
         '<div class="report-note">Contacts were checked against the official portals when this tool was built — confirm on the portal if in doubt.</div></div>';
}

// ── Message / link checker (SMS · WhatsApp · UPI link) ────────────────────
let MSG_MODE = 'sms';
const MSG_HINTS = {
  sms: 'Paste the SMS text. Add the sender ID if you have it (e.g. VK-UIDAI).',
  whatsapp: 'Paste the forwarded WhatsApp message — links and upi:// links inside it are checked too.',
  upi: 'Paste a upi://pay?… link (or the whole message that contains it).',
};
const MSG_ENDPOINT = { sms: '/analyse-sms', whatsapp: '/analyse-whatsapp', upi: '/analyse-upi-link' };

function setMsgMode(mode) {
  MSG_MODE = mode;
  document.querySelectorAll('#msgTabs .msg-tab').forEach(b => b.classList.toggle('active', b.dataset.mode === mode));
  document.getElementById('msgHint').textContent = MSG_HINTS[mode];
  document.getElementById('msgSender').style.display = mode === 'sms' ? 'block' : 'none';
  document.getElementById('msgResult').style.display = 'none';
  const box = document.getElementById('msgExamples');
  box.innerHTML = '';
  MSG_EXAMPLES[mode].forEach(ex => {
    const chip = document.createElement('span');
    chip.className = 'example-chip' + (ex.bad ? ' phish' : '');
    chip.textContent = (ex.bad ? '🚨 ' : '✅ ') + ex.label;
    chip.onclick = () => {
      document.getElementById('msgText').value = ex.text;
      document.getElementById('msgSender').value = ex.sender || '';
    };
    box.appendChild(chip);
  });
}

async function analyseMessage() {
  const text = document.getElementById('msgText').value.trim();
  const sender = document.getElementById('msgSender').value.trim();
  if (!text) { alert('Paste a message or link first.'); return; }
  let r = null;
  try {
    const body = MSG_MODE === 'sms' ? { text, sender } : { text };
    const resp = await fetch(API_BASE + MSG_ENDPOINT[MSG_MODE], {
      method: 'POST', headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify(body), signal: AbortSignal.timeout(4000),
    });
    if (resp.ok) { r = await resp.json(); r.source = 'backend rules'; }
  } catch (e) { /* backend offline — use the in-browser port */ }
  if (!r) {
    r = MSG_MODE === 'sms' ? scoreSMSHeuristic(text, sender)
      : MSG_MODE === 'whatsapp' ? scoreWhatsAppHeuristic(text)
      : scoreUpiFromText(text);
  }
  renderMessageResult(r);
}

function renderMessageResult(r) {
  const div = document.getElementById('msgResult');
  const bad = !!r.is_phishing;
  const warn = !bad && (r.flags || []).length > 0 && r.risk_score >= 0.2;
  const pct = (r.risk_score * 100).toFixed(0);
  const skip = ['flags', 'advice', 'urls_found', 'upi_links_found', 'uri', 'analysed_at', 'source',
                'payee_vpa', 'payee_name', 'note', 'currency', 'amount', 'action'];
  const rows = Object.keys(r).filter(k => skip.indexOf(k) === -1 && typeof r[k] !== 'object')
    .map(k => '<tr><td>' + escHtml(k) + '</td><td>' + escHtml(String(r[k])) + '</td><td></td></tr>').join('');
  const flags = (r.flags || []).map(f => '<li>' + escHtml(f) + '</li>').join('');
  const meta = r.valid_upi_link
    ? '<div class="msg-meta">Payee: <b>' + escHtml(r.payee_vpa) + '</b>' + (r.payee_name ? ' · Name: ' + escHtml(r.payee_name) : '') +
      (r.amount ? ' · Amount: ' + escHtml(r.amount) : '') + '</div>' : '';
  div.innerHTML =
    '<div class="verdict-card ' + (bad ? 'phishing' : 'legit') + '" style="padding:18px;">' +
      '<div class="verdict-icon">' + (bad ? '🚨' : (warn ? '⚠️' : '✅')) + '</div>' +
      '<div class="verdict-label"' + (warn ? ' style="color:var(--warn)"' : '') + '>' + (bad ? 'LIKELY SCAM' : (warn ? 'SOME WARNING SIGNS' : 'NO STRONG SCAM SIGNALS')) + '</div>' +
      '<div class="verdict-conf">Risk score: <strong>' + pct + '%</strong></div>' +
      '<div class="prob-bar-wrap" style="width:100%;margin-top:8px;"><div class="prob-bar-track"><div class="prob-bar-fill" style="width:' + pct + '%"></div></div></div>' +
    '</div>' + meta +
    (flags ? '<ul class="msg-flags">' + flags + '</ul>' : '') +
    (r.advice ? '<div class="msg-advice">' + escHtml(r.advice) + '</div>' : '') +
    (bad ? reportPanelHTML() : '') +
    '<div class="msg-disclaimer">Rule-based check (' + escHtml(r.source || 'rules') + ') — a clean result is not a guarantee of safety.</div>' +
    '<details class="msg-details"><summary>Show raw signals</summary><div class="features-card"><table><tbody>' + rows + '</tbody></table></div></details>';
  div.style.display = 'block';
}

